function build() {
  const parts = [];
  const add = (muscle, pos, scale, rotZ = 0) => parts.push({ muscle, pos, scale, rotZ });
  for (const [muscle, [x, y, z], scale, rot = 0] of TORSO) {
    if (x === 0) add(muscle, [0, y, z], scale, rot);
    else for (const s of [1, -1]) add(muscle, [s * x, y, z], scale, s * rot);
  }
  for (const s of [1, -1]) {
    // 腕は肩を中心に外へ傾ける
    const a = s * ARM_TILT;
    const [cos, sin] = [Math.cos(a), Math.sin(a)];
    for (const [muscle, [x, y, z], scale] of ARM) {
      const lx = s * x;
      add(muscle, [s * SHOULDER[0] + lx * cos - y * sin, SHOULDER[1] + lx * sin + y * cos, z], scale, a);
    }
    for (const [muscle, [x, y, z], scale] of LEG) add(muscle, [s * HIP[0] + x, HIP[1] + y, z], scale);
  }
  return parts;
}

export const PARTS = build();
